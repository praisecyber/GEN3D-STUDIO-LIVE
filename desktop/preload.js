const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('studio', {
  sendVideoSignal: message => ipcRenderer.send('videoSignal', message),
  requestVideoOutput: () => ipcRenderer.send('requestVideoOutput'),
  setOutputMode: mode => ipcRenderer.send('setOutputMode', mode),
  onVideoSignal: f => { const listener = (_e, m) => f(m); ipcRenderer.on('videoSignal', listener); return () => ipcRenderer.removeListener('videoSignal', listener); },
  onOutputMode: f => { const listener = (_e, m) => f(m); ipcRenderer.on('outputMode', listener); return () => ipcRenderer.removeListener('outputMode', listener); },
  listCaptureSources: () => ipcRenderer.invoke('listCaptureSources'),
  selectCaptureSource: id => ipcRenderer.invoke('selectCaptureSource',id),
  pickVisualMedia: () => ipcRenderer.invoke('pickVisualMedia'),
  pickLogo: () => ipcRenderer.invoke('pickLogo'),
  requestProjectionState: () => ipcRenderer.send('requestProjectionState'),
  onProjectionState: f => { const listener=(_e,state)=>f(state);ipcRenderer.on('projectionState',listener);return ()=>ipcRenderer.removeListener('projectionState',listener); },
  ffmpegInfo: () => ipcRenderer.invoke('ffmpegInfo'),
  chooseFFmpeg: () => ipcRenderer.invoke('chooseFFmpeg'),
  startStream: config => ipcRenderer.invoke('startStream',config),
  writeStream: payload => ipcRenderer.invoke('writeStream',payload),
  stopStream: id => ipcRenderer.invoke('stopStream',id),
  onStreamStatus: f => { const listener=(_e,status)=>f(status); ipcRenderer.on('streamStatus',listener); return ()=>ipcRenderer.removeListener('streamStatus',listener); },
  beginRecording: () => ipcRenderer.invoke('beginRecording'),
  writeRecording: payload => ipcRenderer.invoke('writeRecording', payload),
  finishRecording: id => ipcRenderer.invoke('finishRecording', id),
  abortRecording: id => ipcRenderer.invoke('abortRecording', id),
  recordingReadyToClose: () => ipcRenderer.send('recordingReadyToClose'),
  onRecordingCloseRequested: f => { const listener = () => f(); ipcRenderer.on('recordingCloseRequested', listener); return () => ipcRenderer.removeListener('recordingCloseRequested', listener); },
  publish: s => ipcRenderer.send('publish', s),
  onCommand: f => ipcRenderer.on('command', (_e, c) => f(c)),
  onState: f => ipcRenderer.on('state', (_e, s) => f(s)),
  importPptx: () => ipcRenderer.invoke('importPptx'),
  pickMedia: () => ipcRenderer.invoke('pickMedia'),
  exportProject: payload => ipcRenderer.invoke('exportProject', payload),
  importProject: () => ipcRenderer.invoke('importProject'),
  info: () => ipcRenderer.invoke('info'),
  openExternal: url => ipcRenderer.invoke('openExternal', url)
});
